-- WARNING: This schema is for context only and is not meant to be run.
-- It's a readable copy of what's live in Supabase. Table order and
-- constraints may not be valid for execution.
-- Last synced with the live database: 2026-11-08.

CREATE TABLE public.profiles (
  id uuid NOT NULL,
  username text NOT NULL UNIQUE,
  avatar_url text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT profiles_pkey PRIMARY KEY (id),
  CONSTRAINT profiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id) ON DELETE CASCADE
);
CREATE TABLE public.caches (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  title text NOT NULL,
  description text,
  latitude double precision NOT NULL,
  longitude double precision NOT NULL,
  location_name text,
  difficulty smallint NOT NULL DEFAULT '1'::smallint,
  image text,
  is_active boolean NOT NULL DEFAULT true,
  secret_code text NOT NULL,
  created_by uuid DEFAULT auth.uid(),
  CONSTRAINT caches_pkey PRIMARY KEY (id),
  CONSTRAINT difficulty_range CHECK (difficulty >= 1 AND difficulty <= 5),
  CONSTRAINT caches_created_by_fkey FOREIGN KEY (created_by) REFERENCES public.profiles(id) ON DELETE SET NULL
);
CREATE TABLE public.hints (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  cache_id uuid NOT NULL,
  hint_order smallint NOT NULL CHECK (hint_order >= 1 AND hint_order <= 3),
  hint_text text NOT NULL,
  is_ai_generated boolean NOT NULL DEFAULT false,
  CONSTRAINT hints_pkey PRIMARY KEY (id),
  CONSTRAINT one_hint_per_order UNIQUE (cache_id, hint_order),
  CONSTRAINT hints_cache_id_fkey FOREIGN KEY (cache_id) REFERENCES public.caches(id) ON DELETE CASCADE
);
CREATE TABLE public.finds (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  cache_id uuid NOT NULL,
  finder_id uuid NOT NULL,
  rating smallint CHECK (rating >= 1 AND rating <= 5),
  journal_note text,
  photo text,
  CONSTRAINT finds_pkey PRIMARY KEY (id),
  CONSTRAINT one_find_per_person UNIQUE (cache_id, finder_id),
  CONSTRAINT finds_cache_id_fkey FOREIGN KEY (cache_id) REFERENCES public.caches(id) ON DELETE CASCADE,
  CONSTRAINT finds_finder_id_fkey FOREIGN KEY (finder_id) REFERENCES public.profiles(id) ON DELETE CASCADE
);
CREATE TABLE public.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  sender_id uuid NOT NULL,
  receiver_id uuid NOT NULL,
  cache_id uuid,
  content text NOT NULL,
  CONSTRAINT messages_pkey PRIMARY KEY (id),
  CONSTRAINT messages_sender_id_fkey FOREIGN KEY (sender_id) REFERENCES public.profiles(id) ON DELETE CASCADE,
  CONSTRAINT messages_receiver_id_fkey FOREIGN KEY (receiver_id) REFERENCES public.profiles(id) ON DELETE CASCADE,
  CONSTRAINT messages_cache_id_fkey FOREIGN KEY (cache_id) REFERENCES public.caches(id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------------
-- Create a profile automatically when someone signs up.
-- The frontend passes the username at signup:
--   supabase.auth.signUp({ email, password, options: { data: { username } } })
-- Without one, the profile gets a placeholder like "user_1a2b3c4d".
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
begin
  insert into public.profiles (id, username)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'username', 'user_' || left(new.id::text, 8))
  );
  return new;
end;
$$;

-- Only the trigger should run this function, never the API.
REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM anon, authenticated, public;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Row Level Security (RLS)
-- RLS is ON for every table. A table with RLS on and no policies returns
-- nothing to the frontend, so caches/hints/finds/messages are blocked
-- until their policies are added (step 4 of the backend plan).
-- ---------------------------------------------------------------------------
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.caches   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hints    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finds    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Profiles are viewable by everyone"
  ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Users can update their own profile"
  ON public.profiles FOR UPDATE
  USING ((select auth.uid()) = id) WITH CHECK ((select auth.uid()) = id);
-- No INSERT policy on purpose: profiles are only created by the trigger above.
